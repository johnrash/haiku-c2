static const char* kUnknown[7] = {
	"#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"
};


struct GlyphTable {
	uint8	rows[256][8];

	GlyphTable()
	{
		for (int code = 0; code < 256; code++)
			_Set(code, kUnknown);
		for (size_t i = 0; i < sizeof(kGlyphs) / sizeof(kGlyphs[0]); i++)
			_Set(kGlyphs[i].code, kGlyphs[i].rows);
		// the display's own full block, the cursor's row too
		memset(rows[0xff], 0x1f, 8);
	}

	void _Set(int code, const char* const art[7])
	{
		for (int row = 0; row < 7; row++) {
			uint8 bits = 0;
			for (int column = 0; column < 5; column++) {
				if (art[row][column] == '#')
					bits |= 0x10 >> column;
			}
			rows[code][row] = bits;
		}
		rows[code][7] = 0;
	}
};


const uint8*
lcd_glyph(uint8 code)
{
	static const GlyphTable table;
	return table.rows[code];
}
